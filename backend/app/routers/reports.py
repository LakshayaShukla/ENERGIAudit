# ── Style helpers ─────────────────────────────────────────────
def _styles():
    base = getSampleStyleSheet()
    return {
        "brand":    ParagraphStyle("brand",    fontSize=9,  textColor=C_CYAN,  alignment=TA_CENTER, fontName="Helvetica"),
        "title":    ParagraphStyle("title",    fontSize=22, textColor=C_NAVY,  alignment=TA_CENTER, fontName="Helvetica-Bold", spaceAfter=2),
        "subtitle": ParagraphStyle("subtitle", fontSize=9,  textColor=C_SLATE, alignment=TA_CENTER, fontName="Helvetica"),
        "h2":       ParagraphStyle("h2",       fontSize=13, textColor=C_NAVY,  fontName="Helvetica-Bold", spaceBefore=14, spaceAfter=6),
        "h3":       ParagraphStyle("h3",       fontSize=10, textColor=C_CYAN,  fontName="Helvetica-Bold", spaceBefore=8,  spaceAfter=4),
        "body":     ParagraphStyle("body",     fontSize=9,  textColor=C_SLATE, fontName="Helvetica", leading=14, spaceAfter=3),
        "bold":     ParagraphStyle("bold",     fontSize=9,  textColor=C_NAVY,  fontName="Helvetica-Bold", leading=14),
        "small":    ParagraphStyle("small",    fontSize=8,  textColor=C_SLATE, fontName="Helvetica", alignment=TA_CENTER),
        "kpi_val":  ParagraphStyle("kpi_val",  fontSize=18, textColor=C_NAVY,  fontName="Helvetica-Bold", alignment=TA_CENTER, spaceAfter=2),
        "kpi_lbl":  ParagraphStyle("kpi_lbl",  fontSize=7,  textColor=C_SLATE, fontName="Helvetica",      alignment=TA_CENTER, textTransform="uppercase"),
    }


def _page_fn(canvas, doc):
    """Branded header/footer on every page."""
    w, h = A4
    canvas.saveState()
    # Top accent bar
    canvas.setFillColor(C_CYAN)
    canvas.rect(0, h - 8*mm, w, 8*mm, fill=1, stroke=0)
    canvas.setFillColor(C_WHITE)
    canvas.setFont("Helvetica-Bold", 9)
    canvas.drawString(18*mm, h - 5.5*mm, "EnergiAudit")
    canvas.setFont("Helvetica", 8)
    canvas.drawRightString(w - 18*mm, h - 5.5*mm,
                           f"CONFIDENTIAL  |  Generated {datetime.now().strftime('%d %b %Y')}")
    # Bottom accent bar
    canvas.setFillColor(C_LIGHT)
    canvas.rect(0, 0, w, 12*mm, fill=1, stroke=0)
    canvas.setFillColor(C_SLATE)
    canvas.setFont("Helvetica", 7.5)
    canvas.drawCentredString(w / 2, 4*mm,
        "This document is system-generated by the EnergiAudit Platform.  "
        "For queries contact support@energiaudit.in")
    canvas.setFont("Helvetica", 7.5)
    canvas.drawRightString(w - 18*mm, 4*mm, f"Page {doc.page}")
    canvas.restoreState()


def _build_pdf(title: str, subtitle: str, sections: list) -> BytesIO:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4,
                            topMargin=22*mm, bottomMargin=18*mm,
                            leftMargin=18*mm, rightMargin=18*mm)
    s = _styles()
    story = [
        Spacer(1, 4*mm),
        Paragraph(title,    s["title"]),
        Paragraph(subtitle, s["subtitle"]),
        Spacer(1, 3*mm),
        HRFlowable(width="100%", thickness=1.5, color=C_CYAN, spaceAfter=8),
    ]
    for section in sections:
        story.extend(section)
        story.append(Spacer(1, 6))
    doc.build(story, onFirstPage=_page_fn, onLaterPages=_page_fn)
    buf.seek(0)
    return buf


def _kpi_box(label: str, value: str, unit: str = "", accent=None) -> Table:
    """Single KPI cell for a metrics row."""
    accent = accent or C_CYAN
    s = _styles()
    cell = Table([[
        Paragraph(value, s["kpi_val"]),
        Paragraph(f"{unit}<br/><font size='7' color='#475569'>{label}</font>",
                  ParagraphStyle("kv", fontSize=8, textColor=accent,
                                 fontName="Helvetica-Bold", alignment=TA_CENTER))
    ]], colWidths=None)
    return cell


def _kpi_row(items: list) -> Table:
    """Row of KPI boxes: items = [(label, value, unit, accent_color), ...]"""
    s = _styles()
    n = len(items)
    col_w = (A4[0] - 36*mm) / n

    cells = []
    for label, value, unit, accent_c in items:
        c = colors.HexColor(accent_c) if isinstance(accent_c, str) else accent_c
        cells.append([
            Paragraph(value, ParagraphStyle("kv2", fontSize=16, textColor=C_NAVY,
                                            fontName="Helvetica-Bold", alignment=TA_CENTER, spaceAfter=1)),
            Paragraph(unit,  ParagraphStyle("ku",  fontSize=7,  textColor=c,
                                            fontName="Helvetica-Bold", alignment=TA_CENTER, spaceAfter=1)),
            Paragraph(label, ParagraphStyle("kl",  fontSize=7,  textColor=C_SLATE,
                                            fontName="Helvetica",      alignment=TA_CENTER)),
        ])

    row_data = [[Table([[c[0]], [c[1]], [c[2]]], colWidths=[col_w - 8*mm]) for c in cells]]
    tbl = Table(row_data, colWidths=[col_w] * n)
    tbl.setStyle(TableStyle([
        ("BOX",        (0, 0), (-1, -1), 0.5, C_BORDER),
        ("INNERGRID",  (0, 0), (-1, -1), 0.5, C_BORDER),
        ("BACKGROUND", (0, 0), (-1, -1), C_LIGHT),
        ("TOPPADDING",    (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING",   (0, 0), (-1, -1), 6),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 6),
    ]))
    return tbl


def _data_table(headers: list, rows: list, col_widths=None, highlight_col=None) -> Table:
    s = _styles()
    header_cells = [Paragraph(h, ParagraphStyle("th", fontSize=8, textColor=C_WHITE,
                                                fontName="Helvetica-Bold", alignment=TA_CENTER))
                    for h in headers]
    body_cells = [[Paragraph(str(cell), ParagraphStyle("td", fontSize=8.5, textColor=C_NAVY,
                                                        fontName="Helvetica", alignment=TA_CENTER))
                   for cell in row] for row in rows]

    data = [header_cells] + body_cells
    tbl = Table(data, colWidths=col_widths, repeatRows=1)
    style = [
        ("BACKGROUND",    (0, 0), (-1, 0),  C_NAVY),
        ("TEXTCOLOR",     (0, 0), (-1, 0),  C_WHITE),
        ("FONTNAME",      (0, 0), (-1, 0),  "Helvetica-Bold"),
        ("FONTSIZE",      (0, 0), (-1, 0),  8),
        ("ROWBACKGROUNDS",(0, 1), (-1, -1), [C_WHITE, C_LIGHT]),
        ("GRID",          (0, 0), (-1, -1), 0.4, C_BORDER),
        ("ALIGN",         (0, 0), (-1, -1), "CENTER"),
        ("VALIGN",        (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING",    (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    if highlight_col is not None:
        style.append(("TEXTCOLOR", (highlight_col, 1), (highlight_col, -1), C_GREEN))
        style.append(("FONTNAME",  (highlight_col, 1), (highlight_col, -1), "Helvetica-Bold"))
    tbl.setStyle(TableStyle(style))
    return tbl


def _info_table(rows: list) -> Table:
    """Two-column key-value info table."""
    s = _styles()
    data = [[Paragraph(r[0], s["bold"]), Paragraph(r[1], s["body"])] for r in rows]
    tbl = Table(data, colWidths=[6*cm, 11*cm])
    tbl.setStyle(TableStyle([
        ("BACKGROUND",  (0, 0), (0, -1), C_LIGHT),
        ("GRID",        (0, 0), (-1, -1), 0.4, C_BORDER),
        ("FONTSIZE",    (0, 0), (-1, -1), 9),
        ("TOPPADDING",  (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING",(0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
    ]))
    return tbl


