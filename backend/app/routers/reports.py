@router.get("/energy")
def energy_report(
    current_user: models.User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    data = (db.query(models.EnergyData)
            .filter(models.EnergyData.user_id == current_user.id)
            .order_by(models.EnergyData.year, models.EnergyData.month)
            .all())

    s = _styles()
    total_kwh  = sum(d.units_kwh for d in data)
    total_cost = sum(d.cost_inr  for d in data)
    total_co2  = total_kwh * EMISSION_FACTOR
    avg_rate   = (total_cost / total_kwh) if total_kwh else 0
    months_cnt = len(data)

    # KPI row
    kpi = _kpi_row([
        ("Total Energy Consumed", f"{total_kwh:,.0f}", "kWh", "#0284c7"),
        ("Total OpEx",            f"\u20b9{total_cost:,.0f}", "INR", "#059669"),
        ("Avg Tariff Rate",       f"\u20b9{avg_rate:.2f}", "/kWh", "#d97706"),
        ("CO\u2082 Emitted",      f"{total_co2/1000:.2f}", "Tonnes", "#475569"),
    ])

    # Organisation info
    org_tbl = _info_table([
        ["Organisation",   current_user.name],
        ["Email",          current_user.email],
        ["Sector",         str(current_user.org_type or "Not Specified")],
        ["Report Period",  f"{months_cnt} months of metered data"],
        ["Report Date",    datetime.now().strftime("%d %B %Y")],
    ])

    # Data table
    rows = [
        [MONTHS_SHORT[d.month], d.year,
         f"{d.units_kwh:,.1f}",
         f"\u20b9{d.cost_inr:,.0f}",
         f"\u20b9{(d.cost_inr/d.units_kwh):.2f}",
         f"{d.units_kwh * EMISSION_FACTOR:,.1f}"]
        for d in data
    ]
    data_tbl = _data_table(
        ["Month", "Year", "Usage (kWh)", "Cost (INR)", "Tariff (INR/kWh)", "CO\u2082 (kg)"],
        rows,
        col_widths=[2.5*cm, 1.8*cm, 3.5*cm, 3.5*cm, 4*cm, 3.2*cm],
        highlight_col=2,
    )

    sections = [
        [Paragraph("Executive Summary", s["h2"]), kpi, Spacer(1, 8)],
        [Paragraph("Organisation Profile", s["h2"]), org_tbl, Spacer(1, 8)],
        [Paragraph("Monthly Energy Ledger", s["h2"]), data_tbl],
    ]

    buf = _build_pdf(
        "Comprehensive Energy Report",
        f"Prepared for: {current_user.name}  |  Period: {months_cnt} months",
        sections,
    )
    return StreamingResponse(buf, media_type="application/pdf",
                             headers={"Content-Disposition": "attachment; filename=energy_report.pdf"})


@router.get("/audit/{audit_id}")
def audit_report(
    audit_id: int,
    current_user: models.User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    audit = db.query(models.Audit).get(audit_id)
    if not audit:
        raise HTTPException(status_code=404, detail="Audit not found")
    if current_user.role == models.UserRole.client and audit.client_id != current_user.id:
        raise HTTPException(status_code=403, detail="Forbidden")

    s = _styles()
    score = audit.efficiency_score or 0
    savings = audit.estimated_savings_inr or 0
    score_color = "#059669" if score >= 80 else ("#d97706" if score >= 60 else "#dc2626")

    kpi = _kpi_row([
        ("Efficiency Score",     str(score),              "/ 100",      score_color),
        ("Estimated Ann. Savings", f"\u20b9{savings:,.0f}", "INR / year", "#059669"),
        ("Audit Status",         audit.status.value.replace("_", " ").title(), "", "#0284c7"),
    ])

    details_tbl = _info_table([
        ["Audit Reference",  f"#{audit.id}"],
        ["Client",           audit.client.name  if audit.client  else "N/A"],
        ["Assigned Auditor", audit.auditor.name if audit.auditor else "Unassigned"],
        ["Date Requested",   audit.created_at.strftime("%d %B %Y") if audit.created_at else "N/A"],
        ["Date Completed",   audit.updated_at.strftime("%d %B %Y") if audit.updated_at else "Pending"],
        ["Efficiency Score", f"{score}/100"],
        ["Estimated Savings",f"\u20b9{savings:,.0f} per annum"],
    ])

    recs_content = [Paragraph("Findings & Recommendations", s["h2"])]
    if audit.recommendations:
        for i, line in enumerate(audit.recommendations.split("\n"), 1):
            if line.strip():
                recs_content.append(
                    Paragraph(f"{i}.  {line.strip()}", s["body"])
                )
    else:
        recs_content.append(Paragraph("No specific recommendations recorded for this audit.", s["body"]))

    sections = [
        [Paragraph("Audit Performance Summary", s["h2"]), kpi, Spacer(1, 8)],
        [Paragraph("Audit Details", s["h2"]), details_tbl, Spacer(1, 8)],
        recs_content,
    ]

    buf = _build_pdf(
        f"Energy Audit Report  \u2014  #{audit_id}",
        f"Client: {audit.client.name if audit.client else 'N/A'}  |  "
        f"Status: {audit.status.value.replace('_',' ').title()}  |  "
        f"Date: {datetime.now().strftime('%d %B %Y')}",
        sections,
    )
    return StreamingResponse(buf, media_type="application/pdf",
                             headers={"Content-Disposition": f"attachment; filename=audit_report_{audit_id}.pdf"})


@router.get("/carbon")
def carbon_report(
    current_user: models.User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    data = (db.query(models.EnergyData)
            .filter(models.EnergyData.user_id == current_user.id)
            .order_by(models.EnergyData.year, models.EnergyData.month)
            .all())

    s = _styles()
    total_kwh  = sum(d.units_kwh  for d in data)
    total_co2  = total_kwh * EMISSION_FACTOR
    tonnes_co2 = total_co2 / 1000
    trees_needed = total_co2 / 21

    kpi = _kpi_row([
        ("Total Energy",      f"{total_kwh:,.0f}",    "kWh",    "#0284c7"),
        ("Total CO\u2082",    f"{total_co2:,.0f}",    "kg",     "#dc2626"),
        ("Carbon Tonnes",     f"{tonnes_co2:.2f}",    "tCO\u2082", "#d97706"),
        ("Offset Trees Req.", f"{trees_needed:,.0f}", "trees",  "#059669"),
    ])

    context_tbl = _info_table([
        ["Emission Factor",    f"{EMISSION_FACTOR} kg CO\u2082/kWh (India CEA Grid Average)"],
        ["Reporting Standard", "GHG Protocol Scope 2 — Location-Based Method"],
        ["Data Source",        "Metered energy consumption records"],
        ["Report Period",      f"{len(data)} months"],
        ["Report Date",        datetime.now().strftime("%d %B %Y")],
    ])

    rows = [
        [MONTHS_SHORT[d.month], d.year,
         f"{d.units_kwh:,.1f}",
         f"{d.units_kwh * EMISSION_FACTOR:,.1f}",
         f"{(d.units_kwh * EMISSION_FACTOR)/1000:.4f}",
         f"{(d.units_kwh * EMISSION_FACTOR)/21:.1f}"]
        for d in data
    ]
    data_tbl = _data_table(
        ["Month", "Year", "Usage (kWh)", "CO\u2082 (kg)", "CO\u2082 (Tonnes)", "Trees to Offset"],
        rows,
        col_widths=[2.2*cm, 1.8*cm, 3.3*cm, 3.2*cm, 3.5*cm, 4*cm],
        highlight_col=3,
    )

    sections = [
        [Paragraph("Carbon Footprint Summary", s["h2"]), kpi, Spacer(1, 8)],
        [Paragraph("Methodology & Context", s["h2"]), context_tbl, Spacer(1, 8)],
        [Paragraph("Monthly Emissions Breakdown", s["h2"]), data_tbl],
    ]

    buf = _build_pdf(
        "Carbon Impact & Sustainability Report",
        f"Prepared for: {current_user.name}  |  GHG Protocol Scope 2  |  {datetime.now().strftime('%B %Y')}",
        sections,
    )
    return StreamingResponse(buf, media_type="application/pdf",
                             headers={"Content-Disposition": "attachment; filename=carbon_report.pdf"})
